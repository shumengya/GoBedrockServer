// gen_pm_blockprops 从 PocketMine 参考端的方块类里提取方块属性（固体、透明、可替换、
// 可流入、燃烧值），生成 internal/blockrule/props_table.go。在项目根目录运行：
//
//	go run ./scripts/gen_pm_blockprops
package main

import "fmt"
import "go/format"
import "maps"
import "os"
import "path/filepath"
import "regexp"
import "slices"
import "strconv"
import "strings"

const blockDir string = "pocketmine服务器参考/src/pocketmine/block"
const outputPath string = "internal/blockrule/props_table.go"

// 参考端 Block 基类的默认值，子类没覆盖就沿用。
var defaultValues map[string]string = map[string]string{
	"isSolid":         "true",
	"isTransparent":   "false",
	"canBeReplaced":   "false",
	"canBeFlowedInto": "false",
	"getBurnChance":   "0",
	"getBurnAbility":  "0",
}

var methodNames []string = []string{
	"isSolid",
	"isTransparent",
	"canBeReplaced",
	"canBeFlowedInto",
	"getBurnChance",
	"getBurnAbility",
}

var classPattern *regexp.Regexp = regexp.MustCompile(`(?m)^\s*(?:abstract\s+)?class\s+(\w+)\s+extends\s+(\w+)`)
var idPattern *regexp.Regexp = regexp.MustCompile(`protected\s+\$id\s*=\s*self::(\w+)\s*;`)

// 一行可能声明多个常量：const SPONGE = 19, WET_SPONGE = 19;
var constLinePattern *regexp.Regexp = regexp.MustCompile(`(?m)^\s*const\s+([^;]+);`)
var constPartPattern *regexp.Regexp = regexp.MustCompile(`(\w+)\s*=\s*(\d+)`)

// complexMarker 表示方法体不是简单的 return 字面量，需要人工确认。
const complexMarker string = "COMPLEX"

type classInfo struct {
	Name     string
	Parent   string
	IDName   string
	Literals map[string]string
}

func main() {
	var err error = run()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	var ids, idErr = loadBlockIDs()
	if idErr != nil {
		return fmt.Errorf("读取方块 ID: %w", idErr)
	}
	var classes, classErr = loadClasses()
	if classErr != nil {
		return fmt.Errorf("解析方块类: %w", classErr)
	}
	var lines []string = []string{
		"// Code generated by scripts/gen_pm_blockprops; DO NOT EDIT.",
		"",
		"package blockrule",
		"",
		"var propsTable map[byte]Props = map[byte]Props{",
	}
	var complexNotes []string = nil
	var byID map[int]string = map[int]string{}
	var names []string = slices.Sorted(maps.Keys(classes))
	var nameIndex int = 0
	for nameIndex = 0; nameIndex < len(names); nameIndex++ {
		var info *classInfo = classes[names[nameIndex]]
		if info.IDName == "" {
			continue
		}
		var blockID, known = ids[info.IDName]
		if !known {
			complexNotes = append(complexNotes, "未知常量 "+info.IDName+" ("+info.Name+")")
			continue
		}
		var previous, duplicated = byID[blockID]
		if duplicated {
			complexNotes = append(complexNotes, fmt.Sprintf("id %d 重复: %s 与 %s", blockID, previous, info.Name))
		}
		byID[blockID] = info.Name
	}
	var sortedIDs []int = slices.Sorted(maps.Keys(byID))
	var idIndex int = 0
	for idIndex = 0; idIndex < len(sortedIDs); idIndex++ {
		var blockID int = sortedIDs[idIndex]
		var className string = byID[blockID]
		var values map[string]string = map[string]string{}
		var methodIndex int = 0
		for methodIndex = 0; methodIndex < len(methodNames); methodIndex++ {
			var method string = methodNames[methodIndex]
			var literal string = resolveLiteral(classes, className, method)
			if literal == complexMarker {
				complexNotes = append(complexNotes, className+"."+method+" 不是简单字面量，按默认值处理")
				literal = defaultValues[method]
			}
			values[method] = literal
		}
		lines = append(lines, fmt.Sprintf(
			"\t%d: {Solid: %s, Transparent: %s, Replaceable: %s, FlowInto: %s, BurnChance: %s, BurnAbility: %s}, // %s",
			blockID,
			values["isSolid"],
			values["isTransparent"],
			values["canBeReplaced"],
			values["canBeFlowedInto"],
			values["getBurnChance"],
			values["getBurnAbility"],
			className,
		))
	}
	lines = append(lines, "}", "")
	var formatted, formatErr = format.Source([]byte(strings.Join(lines, "\n")))
	if formatErr != nil {
		return fmt.Errorf("格式化生成结果: %w", formatErr)
	}
	var writeErr error = os.WriteFile(outputPath, formatted, 0o644)
	if writeErr != nil {
		return fmt.Errorf("写入 %s: %w", outputPath, writeErr)
	}
	fmt.Printf("生成 %d 个方块属性 -> %s\n", len(sortedIDs), outputPath)
	var noteIndex int = 0
	for noteIndex = 0; noteIndex < len(complexNotes); noteIndex++ {
		fmt.Println("注意:", complexNotes[noteIndex])
	}
	return nil
}

// loadBlockIDs 读 BlockIds.php 里的 const NAME = 数字。
func loadBlockIDs() (map[string]int, error) {
	var raw, err = os.ReadFile(filepath.Join(blockDir, "BlockIds.php"))
	if err != nil {
		return nil, fmt.Errorf("读取 BlockIds.php: %w", err)
	}
	var result map[string]int = map[string]int{}
	var lines [][]string = constLinePattern.FindAllStringSubmatch(string(raw), -1)
	var lineIndex int = 0
	for lineIndex = 0; lineIndex < len(lines); lineIndex++ {
		var parts [][]string = constPartPattern.FindAllStringSubmatch(lines[lineIndex][1], -1)
		var partIndex int = 0
		for partIndex = 0; partIndex < len(parts); partIndex++ {
			var number, convErr = strconv.Atoi(parts[partIndex][2])
			if convErr != nil {
				return nil, fmt.Errorf("解析常量 %s: %w", parts[partIndex][1], convErr)
			}
			result[parts[partIndex][1]] = number
		}
	}
	return result, nil
}

func loadClasses() (map[string]*classInfo, error) {
	var entries, err = os.ReadDir(blockDir)
	if err != nil {
		return nil, fmt.Errorf("列目录 %s: %w", blockDir, err)
	}
	var classes map[string]*classInfo = map[string]*classInfo{}
	var index int = 0
	for index = 0; index < len(entries); index++ {
		var fileName string = entries[index].Name()
		// Block.php 是基类，它的返回值就是上面的默认值，不当作覆盖解析。
		if !strings.HasSuffix(fileName, ".php") || fileName == "Block.php" || fileName == "BlockIds.php" {
			continue
		}
		var info, parseErr = parseFile(filepath.Join(blockDir, fileName))
		if parseErr != nil {
			return nil, parseErr
		}
		if info != nil {
			classes[info.Name] = info
		}
	}
	return classes, nil
}

func parseFile(path string) (*classInfo, error) {
	var raw, err = os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("读取 %s: %w", path, err)
	}
	var text string = string(raw)
	var declared []string = classPattern.FindStringSubmatch(text)
	if declared == nil {
		return nil, nil
	}
	var info *classInfo = &classInfo{Name: declared[1], Parent: declared[2], Literals: map[string]string{}}
	var idMatch []string = idPattern.FindStringSubmatch(text)
	if idMatch != nil {
		info.IDName = idMatch[1]
	}
	var index int = 0
	for index = 0; index < len(methodNames); index++ {
		var literal, found = extractLiteral(text, methodNames[index])
		if found {
			info.Literals[methodNames[index]] = literal
		}
	}
	return info, nil
}

// extractLiteral 取方法 `return 字面量;` 里的字面量；方法存在但写法更复杂时返回 complexMarker。
func extractLiteral(text string, method string) (string, bool) {
	var present *regexp.Regexp = regexp.MustCompile(`function\s+` + method + `\s*\(`)
	if !present.MatchString(text) {
		return "", false
	}
	var simple *regexp.Regexp = regexp.MustCompile(
		`function\s+` + method + `\s*\([^)]*\)\s*(?::\s*\??\w+)?\s*\{\s*return\s+([^;{}]+?)\s*;\s*\}`,
	)
	var match []string = simple.FindStringSubmatch(text)
	if match == nil {
		return complexMarker, true
	}
	var literal string = strings.TrimSpace(match[1])
	if literal == "true" || literal == "false" {
		return literal, true
	}
	var _, convErr = strconv.Atoi(literal)
	if convErr != nil {
		return complexMarker, true
	}
	return literal, true
}

// resolveLiteral 沿继承链向上找第一个覆盖了该方法的类，找不到就用基类默认值。
func resolveLiteral(classes map[string]*classInfo, className string, method string) string {
	var current string = className
	var depth int = 0
	for depth = 0; depth < 32; depth++ {
		var info, known = classes[current]
		if !known {
			break
		}
		var literal, has = info.Literals[method]
		if has {
			return literal
		}
		current = info.Parent
	}
	return defaultValues[method]
}
