package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

type phpClass struct {
	Class     string
	NetworkID int
	Name      string
}

type entry struct {
	ID        int
	Primary   string
	Aliases   []string
	Name      string
	CanSummon bool
}

func main() {
	root := findRoot()
	dir := filepath.Join(root, "pocketmine服务器参考", "src", "pocketmine", "entity")
	classes := parseEntityClasses(dir)

	outDir := filepath.Join(root, "internal", "entity")
	cleanGenerated(outDir, map[string]struct{}{
		"register.go":      {},
		"register_test.go": {},
		"instance.go":      {},
	})
	list := groupEntities(classes)
	writePackage(outDir, list)
	fmt.Printf("generated entities=%d\n", len(list))
}

func findRoot() string {
	wd, err := os.Getwd()
	if err != nil {
		panic(err)
	}
	dir := wd
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			panic("go.mod not found")
		}
		dir = parent
	}
}

var (
	networkIDRe = regexp.MustCompile(`const\s+NETWORK_ID\s*=\s*(-?\d+)`)
	getNameRe   = regexp.MustCompile(`function getName\s*(?::\s*string)?\s*\([^)]*\)[^{]*\{\s*return\s+"([^"]+)"`)
)

func parseEntityClasses(dir string) []phpClass {
	ents, err := os.ReadDir(dir)
	if err != nil {
		panic(err)
	}
	var names []string
	for _, e := range ents {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".php") {
			continue
		}
		names = append(names, e.Name())
	}
	sort.Strings(names)

	out := make([]phpClass, 0, len(names))
	for _, name := range names {
		class := strings.TrimSuffix(name, ".php")
		raw, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			continue
		}
		m := networkIDRe.FindSubmatch(raw)
		if len(m) != 2 {
			continue
		}
		id, _ := strconv.Atoi(string(m[1]))
		if id < 0 {
			continue
		}
		disp := ""
		if n := getNameRe.FindSubmatch(raw); len(n) == 2 {
			disp = string(n[1])
		}
		if disp == "" {
			disp = titleFromCamel(class)
		}
		out = append(out, phpClass{Class: class, NetworkID: id, Name: disp})
	}
	return out
}

func groupEntities(classes []phpClass) []entry {
	byID := map[int][]phpClass{}
	ids := make([]int, 0)
	for _, c := range classes {
		if _, ok := byID[c.NetworkID]; !ok {
			ids = append(ids, c.NetworkID)
		}
		byID[c.NetworkID] = append(byID[c.NetworkID], c)
	}
	sort.Ints(ids)

	out := make([]entry, 0, len(ids))
	for _, id := range ids {
		list := byID[id]
		primary := list[0]
		aliases := make([]string, 0)
		seen := map[string]struct{}{}
		add := func(a string) {
			a = strings.ToLower(strings.TrimSpace(a))
			if a == "" {
				return
			}
			if _, ok := seen[a]; ok {
				return
			}
			seen[a] = struct{}{}
			aliases = append(aliases, a)
		}
		canSummon := true
		for _, c := range list {
			add(c.Class)
			add(camelToSnake(c.Class))
			add(strings.ReplaceAll(c.Name, " ", "_"))
			if c.Class == "Item" || c.Class == "Painting" {
				canSummon = false
			}
			if c.Class == "LavaSlime" {
				add("magma_cube")
				add("magmacube")
			}
			if c.Class == "Item" {
				add("droppeditem")
				add("dropped_item")
			}
		}
		out = append(out, entry{
			ID:        id,
			Primary:   primary.Class,
			Aliases:   aliases,
			Name:      primary.Name,
			CanSummon: canSummon,
		})
	}
	return out
}

func titleFromCamel(s string) string {
	parts := strings.Split(camelToSnake(s), "_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		r := []rune(p)
		r[0] = unicode.ToUpper(r[0])
		parts[i] = string(r)
	}
	return strings.Join(parts, " ")
}

func camelToSnake(s string) string {
	runes := []rune(s)
	var b strings.Builder
	for i, r := range runes {
		if i > 0 && unicode.IsUpper(r) {
			prev := runes[i-1]
			nextLower := i+1 < len(runes) && unicode.IsLower(runes[i+1])
			if unicode.IsLower(prev) || (unicode.IsUpper(prev) && nextLower) {
				b.WriteByte('_')
			}
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}

func cleanGenerated(dir string, keep map[string]struct{}) {
	ents, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			_ = os.MkdirAll(dir, 0o755)
			return
		}
		panic(err)
	}
	for _, e := range ents {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		if _, ok := keep[e.Name()]; ok {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			continue
		}
		if strings.Contains(string(raw), "Code generated by scripts/gen_pm_entities.go") {
			_ = os.Remove(filepath.Join(dir, e.Name()))
		}
	}
}

func writePackage(dir string, list []entry) {
	_ = os.MkdirAll(dir, 0o755)
	used := map[string]int{}
	for _, e := range list {
		file := uniqueFile(camelToSnake(e.Primary), used)
		path := filepath.Join(dir, file+".go")
		aliasLit := strings.Join(quoteAll(e.Aliases), ", ")
		body := fmt.Sprintf(`// Code generated by scripts/gen_pm_entities.go; DO NOT EDIT.

package entity

func init() {
	Register(&Type{
		NetworkID: %d,
		Name:      %q,
		Aliases:   []string{%s},
		CanSummon: %t,
	})
}
`, e.ID, e.Name, aliasLit, e.CanSummon)
		formatted, err := format.Source([]byte(body))
		if err != nil {
			panic(fmt.Errorf("%s: %w", path, err))
		}
		if err := os.WriteFile(path, formatted, 0o644); err != nil {
			panic(err)
		}
	}
}

func uniqueFile(base string, used map[string]int) string {
	base = strings.Map(func(r rune) rune {
		if r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r) {
			return r
		}
		return '_'
	}, base)
	if base == "" || unicode.IsDigit(rune(base[0])) || base == "register" || base == "instance" || strings.HasSuffix(base, "_test") {
		base = "id_" + base
	}
	n := used[base]
	used[base] = n + 1
	if n == 0 {
		return base
	}
	return fmt.Sprintf("%s_%d", base, n)
}

func quoteAll(ss []string) []string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = strconv.Quote(s)
	}
	return out
}
